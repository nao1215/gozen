// Command errgen writes website/content/errors.md, the reference page of the
// diagnostic codes, from internal/diag (ADR 0024). Run it from the module root.
package main

import (
	"fmt"
	"log"
	"os"
	"strconv"
	"strings"

	md "github.com/nao1215/markdown"

	"github.com/nao1215/gozen/internal/diag"
)

func main() {
	if err := os.WriteFile("website/content/errors.md", markdown(), 0o600); err != nil {
		log.New(os.Stderr, "", 0).Print(fmt.Errorf("write the error codes page (run from the module root): %w", err))
		os.Exit(1)
	}
}

// markdown renders the reference page website/content/errors.md (front matter
// included). A test fails when the committed page differs.
func markdown() []byte {
	b := md.NewMarkdown(nil, md.WithBlockSpacing())
	all := diag.All()
	b.PlainText("---\ntitle: Error codes\ndescription: The diagnostic codes of gozen (GZN and four digits) - what each one means, why it is reported, and how to fix it.\nweight: 75\ntoc: true\n---")
	b.PlainText("<!-- Generated by go run ./internal/dev/errgen from internal/diag. Do not edit. -->")
	b.PlainText("A diagnostic of `gozen` can carry a code: `GZN` and four digits at the end of the line, or the `code` field of the JSON output. The message may be reworded; the code does not change, so you can search for it, link to it, and branch on it.")
	b.PlainText("The first digit is the exit value: `GZN0xxx` is a warning and the command still exits 0, `GZN1xxx` exits 1 (processing failed), and `GZN2xxx` exits 2 (the command line is invalid). The next two digits are the family, what you have to fix. Summary lines such as `check: 3 errors` carry no code; the diagnostics they count do.")
	b.PlainText("Run `gozen help GZN1101` to read an entry in the terminal.")
	b.PlainText("Codes are assigned one family at a time. A diagnostic without a code still exits the same way and still says what is wrong.")
	table := md.TableSet{EscapeCells: true, Header: []string{"Codes", "Exit", "Meaning", "Assigned"}}
	for _, f := range diag.Families() {
		n := 0
		for _, e := range all {
			if fmt.Sprintf("GZN%02dxx", int(e.Code)/100) == f.Prefix {
				n++
			}
		}
		assigned := "not yet"
		if n > 0 {
			assigned = fmt.Sprintf("%d codes", n)
		}
		table.Rows = append(table.Rows, []string{md.Code(f.Prefix), strconv.Itoa(f.Exit), f.Meaning, assigned})
	}
	b.Table(table)
	for _, f := range diag.Families() {
		var section []diag.Entry
		for _, e := range all {
			if fmt.Sprintf("GZN%02dxx", int(e.Code)/100) == f.Prefix {
				section = append(section, e)
			}
		}
		if len(section) == 0 {
			continue
		}
		b.H2(f.Prefix).PlainTextf("%s. Exits %d.", upper(f.Meaning), f.Exit)
		for _, e := range section {
			b.H3(e.Code.String()).PlainText(upper(e.Summary) + ".").PlainText(e.Detail).PlainText("Fix: " + e.Fix)
		}
	}
	return []byte(strings.TrimRight(strings.ReplaceAll(b.String(), "\r\n", "\n"), "\n") + "\n")
}

func upper(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}
